let LANG = "fr";

function T(key, vars) {
  let s = (STRINGS[LANG] && STRINGS[LANG][key]) ?? STRINGS.fr[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return s;
}
/* Pluriel : T(key_one) ou T(key_other) selon n. */
function TP(key, n, vars) {
  return T(key + (Math.abs(n) === 1 ? "_one" : "_other"), { n, ...(vars || {}) });
}
/* Traduit un message libre venu du serveur, s'il est connu. */
function trMsg(s) {
  if (!s || LANG === "fr") return s || "";
  for (const [re, key] of SERVER_MSGS) {
    const m = String(s).match(re);
    if (m) return T(key, { x: m[1] });
  }
  return s;
}
/* Diagnostic d'analyse ({kind, scene}) dans la langue courante. */
function diagText(d) {
  if (!d) return "?";
  if (!d.kind) return d.type || "?";
  let s = T("kind." + d.kind);
  if (d.scene && d.scene.length) s += " ; " + d.scene.map(c => T("scene." + c)).join(", ");
  return s;
}
function pickLang(saved) {
  if (saved && STRINGS[saved]) return saved;
  try { const ls = localStorage.getItem("aquimage.lang"); if (ls && STRINGS[ls]) return ls; } catch (e) {}
  const nav = (navigator.language || "fr").slice(0, 2).toLowerCase();
  return STRINGS[nav] ? nav : "fr";
}
/* Applique les attributs data-i18n* de la page. */
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = T(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = T(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach(el => { el.title = T(el.dataset.i18nTitle); });
  root.querySelectorAll("[data-i18n-aria]").forEach(el => { el.setAttribute("aria-label", T(el.dataset.i18nAria)); });
  root.querySelectorAll("[data-i18n-alt]").forEach(el => { el.alt = T(el.dataset.i18nAlt); });
}
